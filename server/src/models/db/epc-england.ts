export const $epcEngland = {
    TABLE_NAME: `epc_data_england`,
    knex: (session = $pg) => {
        return session.table<EpcCertificate>($epcEngland.TABLE_NAME);
    },
    latestByUprn: () => {
        return $epcEngland
            .knex()
            .distinctOn("uprn")
            .orderBy([
                {
                    column: "uprn",
                    order: "asc",
                },
                {
                    column: "lodgement_date",
                    order: "desc",
                },
            ]);
    },
};
